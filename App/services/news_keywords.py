# ============================================================
# 用户覆盖（页面 UI 维护，存在 news_keyword_overrides 表）
# ============================================================
# 缓存进程级；任何写覆盖的 API 调用都要 invalidate_overrides_cache()
_overrides_cache: dict | None = None


def _load_overrides() -> dict:
    """从 DB 拉用户的词表覆盖，返回 {'stopwords': set, 'finance': set}"""
    global _overrides_cache
    if _overrides_cache is not None:
        return _overrides_cache
    try:
        from App.models.data.news import NewsKeywordOverride
        rows = NewsKeywordOverride.query.all()
        _overrides_cache = {
            'stopwords': {r.term for r in rows if r.action == 'stopword'},
            'finance': {r.term for r in rows if r.action == 'finance'},
        }
    except Exception as e:
        logger.warning(f'读取关键词覆盖失败（按空集处理）: {e}')
        _overrides_cache = {'stopwords': set(), 'finance': set()}
    return _overrides_cache


def invalidate_overrides_cache() -> None:
    """清缓存。任何 INSERT/DELETE news_keyword_overrides 后必须调用。"""
    global _overrides_cache
    _overrides_cache = None


def get_effective_stopwords() -> Set[str]:
    """硬编码 STOPWORDS ∪ 用户覆盖（stopword）"""
    return STOPWORDS | _load_overrides()['stopwords']


def get_effective_finance_terms() -> Set[str]:
    """硬编码 FINANCE_TERMS ∪ 用户覆盖（finance）
    再减去被用户强制设为停用词的（停用词优先级最高）"""
    ov = _load_overrides()
    return (FINANCE_TERMS | ov['finance']) - ov['stopwords']


