# 主接口
# ============================================================

def extract_finance_keywords(text: str, top_k: int = 8,
                              min_len: int = 2) -> List[Tuple[str, float, bool]]:
    """从一段文本提取财经相关关键词。

    流程：
      1. jieba.posseg 切词 + 词性过滤
      2. 过滤停用词、短词、纯数字
      3. 命中财经词表 → 权重 ×2
      4. 用 TF（频次）排序（不用 TF-IDF，因为我们是单文档场景）

    Returns:
        [(word, weight, is_finance_term)]，按 weight 降序
    """
    if not text or len(text) < 4:
        return []

    import jieba.posseg as pseg

    eff_stopwords = get_effective_stopwords()
    eff_finance = get_effective_finance_terms()

    counts: dict[str, int] = {}
    pos_keep: dict[str, bool] = {}

    for word, flag in pseg.cut(text):
        word = word.strip()
        if len(word) < min_len:
            continue
        if word.isdigit():
            continue
        # 词性显式拒绝优先
        if flag in _REJECTED_POS:
            continue
        # 不在白名单里的词性也丢
        # 注意：jieba 的词性会带后缀（如 "n", "ns"），用前缀判断更宽松
        flag_root = flag.rstrip('1234567890')
        if flag_root not in _ALLOWED_POS:
            continue
        # 停用词（含用户覆盖）—— 优先级最高
        if word in eff_stopwords:
            continue
        # 包含非中英文字符（如纯标点）跳过
        if not re.search(r'[一-鿿\w]', word):
            continue

        counts[word] = counts.get(word, 0) + 1
        pos_keep[word] = True

    # 排序：频次 × 财经加权（用 effective_finance，含用户覆盖）
    scored: List[Tuple[str, float, bool]] = []
    for word, cnt in counts.items():
        is_fin = word in eff_finance
        weight = float(cnt) * (2.0 if is_fin else 1.0)
        scored.append((word, weight, is_fin))

    scored.sort(key=lambda x: x[1], reverse=True)
    return scored[:top_k]
